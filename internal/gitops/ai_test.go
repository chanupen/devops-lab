package gitops

import (
	"slices"
	"strings"
	"testing"

	"sigs.k8s.io/yaml"
)

func toYAML(o map[string]any) string {
	b, _ := yaml.Marshal(o)
	return string(b)
}

// ai: the ollama Service, the ClickHouse operator, Langfuse's
// ExternalSecrets, Langfuse and its route, in sync-wave order, all in the
// ai namespace.
func TestBootstrapChartAI(t *testing.T) {
	objs := render(t, map[string]any{"ai": true}, "lab-zot:5000")
	tests := []struct {
		app, wave, repo string
	}{
		{"ollama", "0", ""},
		{"clickhouse-operator", "0", "lab-zot:5000/ghcr.io/clickhouse"},
		{"langfuse-secrets", "1", ""},
		{"langfuse", "2", "https://langfuse.github.io/langfuse-k8s"},
		{"ai-routes", "3", ""},
	}
	for _, tt := range tests {
		o, ok := objs["Application/"+tt.app]
		if !ok {
			t.Fatalf("%s not rendered", tt.app)
		}
		if field(o, "spec", "destination", "namespace") != AINamespace || field(o, "metadata", "labels", StackLabel) != "ai" ||
			field(o, "metadata", "annotations", "argocd.argoproj.io/sync-wave") != tt.wave {
			t.Errorf("%s = %v %v", tt.app, o["metadata"], field(o, "spec", "destination"))
		}
		if tt.repo != "" {
			srcs, _ := field(o, "spec", "sources").([]any)
			if len(srcs) != 2 || srcs[0].(map[string]any)["repoURL"] != tt.repo {
				t.Errorf("%s chart source = %v, want %s", tt.app, srcs, tt.repo)
			}
		}
	}
	opts, _ := field(objs["Application/langfuse"], "spec", "syncPolicy", "syncOptions").([]any)
	if !slices.Contains(opts, any("SkipDryRunOnMissingResource=true")) {
		t.Errorf("langfuse syncOptions = %v: its ClickHouseCluster needs the operator's CRDs", opts)
	}
	for name := range render(t, map[string]any{"ai": false}, "") {
		if strings.HasPrefix(name, "Application/") && (strings.Contains(name, "langfuse") || strings.Contains(name, "ollama")) {
			t.Errorf("ai off renders %s", name)
		}
	}
}

// Local mode: ollama.ai.svc has no selector (lab writes its EndpointSlice),
// and only labelled pods in the ai namespace may reach Ollama's address.
// Langfuse keeps raw events in Moto's S3 and takes every credential from
// ESO. Cloud mode is a stub: no policy without an address, no Moto.
func TestRenderAI(t *testing.T) {
	find := func(mode, kind, name string) map[string]any {
		for _, o := range renderMode(t, mode) {
			if o.Obj["kind"] == kind && field(o.Obj, "metadata", "name") == name {
				return o.Obj
			}
		}
		return nil
	}
	svc := find("local", "Service", "ollama")
	if svc == nil || field(svc, "spec", "selector") != nil {
		t.Fatalf("Service ollama = %v, want one without a selector", svc)
	}
	np := find("local", "NetworkPolicy", "ollama-labelled-pods-only")
	if np == nil {
		t.Fatal("no NetworkPolicy for Ollama in local mode")
	}
	exprs, _ := field(np, "spec", "podSelector", "matchExpressions").([]any)
	egress, _ := field(np, "spec", "egress").([]any)
	if len(exprs) != 1 || len(egress) != 1 || !strings.Contains(toYAML(np), "- 10.89.1.250/32") {
		t.Errorf("NetworkPolicy = %s", toYAML(np))
	}
	if e := exprs[0].(map[string]any); e["key"] != "lab.devops/ollama" || e["operator"] != "NotIn" {
		t.Errorf("podSelector = %v", exprs)
	}
	if find("cloud", "NetworkPolicy", "ollama-labelled-pods-only") != nil {
		t.Error("cloud mode renders the Ollama policy without an address")
	}
	web := find("local", "Deployment", "langfuse-web")
	if web == nil {
		t.Fatal("langfuse-web not rendered")
	}
	y := toYAML(web)
	for _, want := range []string{"http://lab-moto:5000", "name: langfuse-credentials", "docker.io/langfuse/langfuse:4.75.0@sha256:"} {
		if !strings.Contains(y, want) {
			t.Errorf("langfuse-web lacks %q", want)
		}
	}
	// Argo CD renders without the cluster: nothing may be generated by the
	// chart, or it would change on every sync.
	for _, o := range renderMode(t, "local") {
		if o.Obj["kind"] == "Secret" && o.App == "langfuse" {
			if d, _ := o.Obj["data"].(map[string]any); len(d) > 0 {
				t.Errorf("langfuse renders Secret %v with data: credentials must come from ESO", field(o.Obj, "metadata", "name"))
			}
		}
	}
}
