// StateKey is where the baseline keeps its own state in the state bucket.
const StateKey = "baseline/terraform.tfstate"

// StateBucket is the state bucket's name for an account.
func StateBucket(account string) string { return "lab-tofu-state-" + account }

// Baseline runs the account baseline module with OpenTofu through
// terraform-exec. The module is copied from the repo into WorkDir, so the
// local state of the first run, plans and .terraform never land in the repo.
type Baseline struct {
	ModuleDir string            // infra/terraform/aws/baseline in the repo
	WorkDir   string            // ~/.lab/tofu/baseline
	Tofu      string            // path to the tofu binary
	VarFile   string            // private tfvars (alert_email); never in the repo
	Vars      map[string]any    // owner, reaper_zip, ...
	Env       map[string]string // AWS credentials for tofu, from Session.Env
	Account   string
	Config    aws.Config // for the state bucket check
	Out       io.Writer  // tofu's output
}

// PlanFile is the saved plan Apply runs.
func (b *Baseline) PlanFile() string { return filepath.Join(b.WorkDir, "baseline.tfplan") }

// Remote reports whether the state lives in the state bucket. Before the
// first apply the bucket does not exist and the state is local in WorkDir.
func (b *Baseline) Remote(ctx context.Context) (bool, error) {
	_, err := s3.NewFromConfig(b.Config).HeadBucket(ctx, &s3.HeadBucketInput{Bucket: aws.String(StateBucket(b.Account))})
	if err == nil {
		return true, nil
	}
	if strings.Contains(err.Error(), "NotFound") || strings.Contains(err.Error(), "StatusCode: 404") {
		return false, nil
	}
	return false, fmt.Errorf("check state bucket %s: %w", StateBucket(b.Account), err)
}

// prepare copies the module into WorkDir, writes the backend and the
// generated variables, and runs tofu init. With the bucket present and a
// local state left from the first apply, init migrates it into the bucket.
func (b *Baseline) prepare(ctx context.Context) (*tfexec.Terraform, bool, error) {
	if err := os.MkdirAll(b.WorkDir, 0o700); err != nil {
		return nil, false, err
	}
	if err := b.syncModule(); err != nil {
		return nil, false, err
	}
	remote, err := b.Remote(ctx)
	if err != nil {
		return nil, false, err
	}
	backend := filepath.Join(b.WorkDir, "backend.tf")
	if remote {
		hcl := fmt.Sprintf(`# Generated by lab: the state bucket exists, so state lives there.
terraform {
  backend "s3" {
    bucket       = %q
    key          = %q
    region       = %q
    encrypt      = true
    use_lockfile = true
  }
}
`, StateBucket(b.Account), StateKey, Region)
		if err := os.WriteFile(backend, []byte(hcl), 0o600); err != nil {
			return nil, false, err
		}
	} else if err := os.Remove(backend); err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, false, err
	}
	vars, err := json.MarshalIndent(b.Vars, "", "  ")
	if err != nil {
		return nil, false, err
	}
	if err := os.WriteFile(filepath.Join(b.WorkDir, "lab.auto.tfvars.json"), vars, 0o600); err != nil {
		return nil, false, err
	}
	tf, err := tfexec.NewTerraform(b.WorkDir, b.Tofu)
	if err != nil {
		return nil, false, err
	}
	if err := tf.SetEnv(b.env()); err != nil {
		return nil, false, err
	}
	if b.Out != nil {
		tf.SetStdout(b.Out)
		tf.SetStderr(b.Out)
	}
	// ForceCopy answers yes to moving a local state into the bucket.
	if err := tf.Init(ctx, tfexec.ForceCopy(true)); err != nil {
		return nil, false, fmt.Errorf("tofu init: %w", err)
	}
	return tf, remote, nil
}

func (b *Baseline) env() map[string]string { return tofuEnv(b.Env) }

func (b *Baseline) syncModule() error { return syncModule(b.ModuleDir, b.WorkDir) }

// Plan writes a saved plan and returns whether it changes anything, and
// whether the state is already in the bucket.
func (b *Baseline) Plan(ctx context.Context) (changes, remote bool, err error) {
	tf, remote, err := b.prepare(ctx)
	if err != nil {
		return false, false, err
	}
	opts := []tfexec.PlanOption{tfexec.Out(b.PlanFile())}
	if b.VarFile != "" {
		opts = append(opts, tfexec.VarFile(b.VarFile))
	}
	changes, err = tf.Plan(ctx, opts...)
	if err != nil {
		return false, remote, fmt.Errorf("tofu plan: %w", err)
	}
	if changes {
		// A missing managed policy fails the plan, so apply never starts.
		tf.SetStdout(io.Discard)
		plan, err := tf.ShowPlanFile(ctx, b.PlanFile())
		if err != nil {
			return false, remote, fmt.Errorf("read the saved plan: %w", err)
		}
		out := b.Out
		if out == nil {
			out = io.Discard
		}
		if err := checkPlanPolicies(ctx, b.Config, plan, out); err != nil {
			return false, remote, err
		}
	}
	return changes, remote, nil
}

// Apply runs the saved plan, then, if the state was still local, moves it
// into the bucket the apply just created.
func (b *Baseline) Apply(ctx context.Context) (migrated bool, err error) {
	tf, remote, err := b.prepare(ctx)
	if err != nil {
		return false, err
	}
	if err := tf.Apply(ctx, tfexec.DirOrPlan(b.PlanFile())); err != nil {
		return false, fmt.Errorf("tofu apply: %w", err)
	}
	_ = os.Remove(b.PlanFile()) // a plan is good for one apply
	if remote {
		return false, nil
	}
	// The bucket exists now: prepare writes the S3 backend and init moves
	// the local state into it.
	if _, now, err := b.prepare(ctx); err != nil || !now {
		if err == nil {
			err = errors.New("state bucket still missing after apply")
		}
		return false, fmt.Errorf("migrate state to the bucket: %w", err)
	}
	return true, nil
}

// Outputs returns the baseline's outputs as strings.
func (b *Baseline) Outputs(ctx context.Context) (map[string]string, error) {
	tf, err := tfexec.NewTerraform(b.WorkDir, b.Tofu)
	if err != nil {
		return nil, err
	}
	if err := tf.SetEnv(b.env()); err != nil {
		return nil, err
	}
	outs, err := tf.Output(ctx)
	if err != nil {
		return nil, err
	}
	m := map[string]string{}
	for k, o := range outs {
		var s any
		if json.Unmarshal(o.Value, &s) == nil {
			m[k] = fmt.Sprint(s)
		}
	}
	return m, nil
}

// ShowPlan returns the saved plan as tofu prints it.
func (b *Baseline) ShowPlan(ctx context.Context) (string, error) {
	tf, err := tfexec.NewTerraform(b.WorkDir, b.Tofu)
	if err != nil {
		return "", err
	}
	if err := tf.SetEnv(b.env()); err != nil {
		return "", err
	}
	return tf.ShowPlanFileRaw(ctx, b.PlanFile())
}
