// Module runs one OpenTofu root module whose state lives in the state
// bucket: the cloud lab's registry and cluster stacks. Like the baseline,
// the module is copied into WorkDir so plans, .terraform and generated
// files never land in the repo.
type Module struct {
	ModuleDir string            // e.g. infra/terraform/aws/cluster
	WorkDir   string            // e.g. ~/.lab/tofu/cluster
	Tofu      string            // path to the tofu binary
	Bucket    string            // the baseline's state bucket
	Key       string            // state object key, e.g. cluster/terraform.tfstate
	Vars      map[string]any    // written to lab.auto.tfvars.json
	Env       map[string]string // AWS credentials for tofu, from Session.Env
	Out       io.Writer         // tofu's output
	// BeforeApply runs after the plan and before tofu apply, with the work
	// dir ready: the cloud provider uploads the teardown bundle there.
	BeforeApply func(ctx context.Context, workDir string) error
}

// PlanFile is the saved plan Apply runs.
func (m *Module) PlanFile() string { return filepath.Join(m.WorkDir, "lab.tfplan") }

// prepare copies the module, writes the S3 backend and the variables, and
// runs tofu init.
func (m *Module) prepare(ctx context.Context) (*tfexec.Terraform, error) {
	if m.Bucket == "" || m.Key == "" {
		return nil, fmt.Errorf("module %s: no state bucket or key", m.ModuleDir)
	}
	if err := os.MkdirAll(m.WorkDir, 0o700); err != nil {
		return nil, err
	}
	if err := syncModule(m.ModuleDir, m.WorkDir); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(m.WorkDir, "backend.tf"), []byte(backendHCL(m.Bucket, m.Key)), 0o600); err != nil {
		return nil, err
	}
	vars, err := json.MarshalIndent(m.Vars, "", "  ")
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(m.WorkDir, "lab.auto.tfvars.json"), vars, 0o600); err != nil {
		return nil, err
	}
	tf, err := m.tofu()
	if err != nil {
		return nil, err
	}
	if err := tf.Init(ctx); err != nil {
		return nil, fmt.Errorf("tofu init: %w", err)
	}
	return tf, nil
}

func (m *Module) tofu() (*tfexec.Terraform, error) {
	tf, err := tfexec.NewTerraform(m.WorkDir, m.Tofu)
	if err != nil {
		return nil, err
	}
	if err := tf.SetEnv(tofuEnv(m.Env)); err != nil {
		return nil, err
	}
	if m.Out != nil {
		tf.SetStdout(m.Out)
		tf.SetStderr(m.Out)
	}
	return tf, nil
}

// Plan writes a saved plan and reports whether it changes anything.
func (m *Module) Plan(ctx context.Context) (bool, error) {
	tf, err := m.prepare(ctx)
	if err != nil {
		return false, err
	}
	changes, err := tf.Plan(ctx, tfexec.Out(m.PlanFile()))
	if err != nil {
		return false, fmt.Errorf("tofu plan: %w", err)
	}
	return changes, nil
}

// Apply plans and applies that plan. lab asks before it calls Apply.
func (m *Module) Apply(ctx context.Context) error {
	changes, err := m.Plan(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(m.PlanFile()) }() // a plan is good for one apply
	if !changes {
		return nil
	}
	if m.BeforeApply != nil {
		if err := m.BeforeApply(ctx, m.WorkDir); err != nil {
			return err
		}
	}
	tf, err := m.tofu()
	if err != nil {
		return err
	}
	if err := tf.Apply(ctx, tfexec.DirOrPlan(m.PlanFile())); err != nil {
		return fmt.Errorf("tofu apply: %w", err)
	}
	return nil
}

// Destroy removes everything in the module's state.
func (m *Module) Destroy(ctx context.Context) error {
	tf, err := m.prepare(ctx)
	if err != nil {
		return err
	}
	if err := tf.Destroy(ctx); err != nil {
		return fmt.Errorf("tofu destroy: %w", err)
	}
	return nil
}

// Outputs returns the module's outputs as strings.
func (m *Module) Outputs(ctx context.Context) (map[string]string, error) {
	tf, err := m.tofu()
	if err != nil {
		return nil, err
	}
	tf.SetStdout(io.Discard)
	outs, err := tf.Output(ctx)
	if err != nil {
		return nil, err
	}
	res := map[string]string{}
	for k, o := range outs {
		var v any
		if json.Unmarshal(o.Value, &v) == nil {
			res[k] = fmt.Sprint(v)
		}
	}
	return res, nil
}

// ShowPlan returns the saved plan as tofu prints it.
func (m *Module) ShowPlan(ctx context.Context) (string, error) {
	tf, err := m.tofu()
	if err != nil {
		return "", err
	}
	tf.SetStdout(io.Discard)
	return tf.ShowPlanFileRaw(ctx, m.PlanFile())
}

func backendHCL(bucket, key string) string {
	return fmt.Sprintf(`# Generated by lab: state lives in the baseline's state bucket.
terraform {
  backend "s3" {
    bucket       = %q
    key          = %q
    region       = %q
    encrypt      = true
    use_lockfile = true
  }
}
`, bucket, key, Region)
}

// tofuEnv is the process environment without AWS profile or TF settings,
// plus the session's credentials, so tofu uses exactly the session lab
// resolved and a stray AWS_PROFILE cannot redirect it.
func tofuEnv(extra map[string]string) map[string]string {
	env := map[string]string{}
	for _, kv := range os.Environ() {
		k, v, _ := strings.Cut(kv, "=")
		if strings.HasPrefix(k, "AWS_") || strings.HasPrefix(k, "TF_") {
			continue
		}
		env[k] = v
	}
	for k, v := range extra {
		env[k] = v
	}
	return env
}

// syncModule copies a module's .tf, .json (policy documents) and .sh
// (scripts the module uploads) files and
// its provider lock file into workDir, and removes .tf files the module no
// longer has, keeping the generated backend.tf. Subdirectories (another
// root module) are not copied.
func syncModule(moduleDir, workDir string) error {
	tfs, err := filepath.Glob(filepath.Join(moduleDir, "*.tf"))
	if err != nil {
		return err
	}
	if len(tfs) == 0 {
		return fmt.Errorf("no .tf files in %s", moduleDir)
	}
	jsons, _ := filepath.Glob(filepath.Join(moduleDir, "*.json"))
	scripts, _ := filepath.Glob(filepath.Join(moduleDir, "*.sh"))
	want := map[string]bool{"backend.tf": true}
	for _, f := range append(append(tfs, jsons...), scripts...) {
		name := filepath.Base(f)
		switch name {
		case "backend.tf":
			return fmt.Errorf("%s: backend.tf is generated by lab; remove it from the module", f)
		case "lab.auto.tfvars.json":
			return fmt.Errorf("%s: lab.auto.tfvars.json is generated by lab; remove it from the module", f)
		}
		data, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		want[name] = true
		if err := os.WriteFile(filepath.Join(workDir, name), data, 0o600); err != nil {
			return err
		}
	}
	// The provider lock file pins provider versions and hashes.
	if lock, err := os.ReadFile(filepath.Join(moduleDir, ".terraform.lock.hcl")); err == nil {
		if err := os.WriteFile(filepath.Join(workDir, ".terraform.lock.hcl"), lock, 0o600); err != nil {
			return err
		}
	}
	old, _ := filepath.Glob(filepath.Join(workDir, "*.tf"))
	for _, f := range old {
		if !want[filepath.Base(f)] {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}

// Bundle zips what tofu needs to destroy the module without lab: the .tf
// files (with the generated backend), the variables lab wrote, policy
// files and the provider lock file. No state, plans or .terraform.
func Bundle(workDir string) ([]byte, error) {
	var names []string
	for _, pat := range []string{"*.tf", "*.json", ".terraform.lock.hcl"} {
		m, err := filepath.Glob(filepath.Join(workDir, pat))
		if err != nil {
			return nil, err
		}
		names = append(names, m...)
	}
	sort.Strings(names)
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for _, f := range names {
		data, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		w, err := zw.CreateHeader(&zip.FileHeader{Name: filepath.Base(f), Method: zip.Deflate})
		if err != nil {
			return nil, err
		}
		if _, err := w.Write(data); err != nil {
			return nil, err
		}
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
